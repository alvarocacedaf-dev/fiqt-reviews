// Run after changing a bundled bank, before deploying. This preserves all pool
// versions from Git so old compact sequence records can be interpreted.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const banks = ['bfi01-pc1','bfi01-pc2','qu328-final'];
const rows = new Map();
for (const bank of banks) {
  const file = `data/question-banks/${bank}.json`;
  const revisions = execFileSync('git', ['log', '--format=%H', '--', file], { encoding: 'utf8' }).trim().split(/\s+/).filter(Boolean);
  const versions = [readFileSync(file, 'utf8'), ...revisions.map(revision => execFileSync('git', ['show', `${revision}:${file}`], { encoding: 'utf8', maxBuffer: 10_000_000 }))];
  for (const version of versions) {
    const keys = [...new Set(JSON.parse(version).questions.filter(q => q.status === 'reviewed').map(q => q.duplicateKey))].sort((a,b) => a.localeCompare(b,'en'));
    const fingerprint = createHash('sha256').update(JSON.stringify(keys)).digest('hex');
    const quote = value => `'${value.replaceAll("'", "''")}'`;
    rows.set(`${bank}:${fingerprint}`, `(${quote(bank)},${quote(fingerprint)},array[${keys.map(quote).join(',')}])`);
  }
}
writeFileSync('supabase/migrations/068_seed_exam_history_pools.sql', '-- Generated by scripts/question-bank/seed-history-pools.mjs. Preserve historical versions.\ninsert into public.exam_bank_pools(bank_key,fingerprint,keys) values\n' + [...rows.values()].join(',\n') + '\non conflict do nothing;\n');
console.log(`Prepared ${rows.size} historical pools.`);
